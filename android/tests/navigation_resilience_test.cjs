'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const js=read('app/src/main/assets/app.js');
const html=read('app/src/main/assets/index.html');
const css=read('app/src/main/assets/styles.css');
const main=read('app/src/main/java/uk/co/bengoodman/clearroute/MainActivity.java');
const service=read('app/src/main/java/uk/co/bengoodman/clearroute/NavigationService.java');
const api=read('app/src/main/java/uk/co/bengoodman/clearroute/ApiClient.java');
function has(str,expr,label){assert.ok(str.includes(expr),label);}
has(css,'max-height: min(50dvh, 50vh) !important','sheet max height');
for(const id of ['route-sheet','transit-detail-sheet','bus-service-sheet','bus-stop-sheet'])
  has(css,'.'+id,'sheet '+id);
for(const id of ['installedVersionLabel','updateStatusTitle','updateStatusDetail','updateAvailableCard','checkUpdatesBtn'])
  has(html,'id="'+id+'"','update UI '+id);
has(js,'native()?.getInstalledAppVersion','dynamic installed version');
has(main,'@JavascriptInterface public String getInstalledAppVersion()','Java current version');
has(js,"show('routeCard',false);show('busServiceSheet',false);show('busStopSheet',false);",'PT single sheet');
has(js,'desaturateTransitJourney();','muted journey line');
has(js,'clipTransitLegGeometry((leg?.points||[])','slice full bus geometry');
has(js,'getContactMapCandidates','contacts bulk map method');
has(js,'contactsMapGeocodingConsent','geocoding consent');
has(main,'out.length() < 15','bounded contacts');
has(js,'contactGeocodeAttempted.has(key)','rate limit geocoding');
has(main,'state.put("remainingWaypoints", via)','planned stops persisted');
has(service,'state.put("remainingWaypoints", pending)','reroutes preserve stops');
has(service,'for(int i=1;i<pending.length();i++)','reached stop advances queue');
has(api,'routeWithStopsSync','multi stop routing');
has(js,'calculateRouteWithStopsFrom','route planning with ordered stops');
has(js,'startNavigationWithStops','start navigation preserving planned stops');
const first=js.indexOf('function clipTransitLegGeometry(');
const last=js.indexOf('function desaturateTransitJourney()',first);
assert.ok(first>0&&last>first,'clipping helper exists');
const clip=vm.runInNewContext(js.slice(first,last)+'\nclipTransitLegGeometry');
const p=[[-1,0],[0,0],[1,0],[2,0],[3,0]];
const leg={stops:[{lat:0,lon:0},{lat:0,lon:2}]};
const trimmed=clip(p,leg);
assert.equal(trimmed[0][0],0,'bus line must start at boarding');
assert.equal(trimmed.at(-1)[0],2,'bus line must end at alighting');
assert.ok(trimmed.length<=4,'bus line must exclude parts before or after journey');
const projected=clip([[-1,0],[1,0],[3,0]],leg);
assert.equal(projected[0][0],0,'boarding point projected onto segment');
assert.equal(projected.at(-1)[0],2,'alighting point projected onto segment');
const reversed=clip(p,{stops:[{lat:0,lon:2},{lat:0,lon:0}]});
assert.equal(reversed[0][0],2,'reversed service geometry cannot include before-boarding section');
console.log('OpenRoad 0.6.38 navigation resilience: 29 source and route-geometry assertions passed.');
